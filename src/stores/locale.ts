const messages: Record<AppLanguage, Record<TranslationKey, string>> = { ja, en }

export const useLocaleStore = defineStore('locale', () => {
  const stored = typeof localStorage === 'undefined' ? null : localStorage.getItem('vertex.language')
  const language = ref<AppLanguage>(stored === 'en' ? 'en' : 'ja')

  function t(key: TranslationKey) {
    return messages[language.value][key]
  }

  watch(language, (value) => localStorage.setItem('vertex.language', value))

  return { language, t }
})
